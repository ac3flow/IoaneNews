/** Build a translator for one language. Falls back to English, then to the key itself. */
export function makeT(lang) {
  const table = DICT[lang] ?? DICT[DEFAULT_LANG];
  return (key, vars) => {
    const s = table[key] ?? DICT.en[key] ?? key;
    return vars ? s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] === undefined ? `{${k}}` : String(vars[k]))) : s;
  };
}

/** "3 stories" / "1 story": picks the .one or .other form (English only differs). */
export function plural(t, base, n) {
  return t(`${base}.${n === 1 ? 'one' : 'other'}`, { n });
}
